#!/usr/bin/env node
/**
 * Downloads the Leaflet 1.9.4 dist build and writes it to
 * `src/map/leafletAssets.ts` so the in-app map never depends on a CDN.
 *
 * Only the map *engine* is bundled. Map tiles still come from OpenStreetMap
 * when the device is online; when it is not, the bundled engine renders the
 * synthetic coverage, markers and routes over whatever tiles are cached.
 *
 * Re-run:  node tools/bundle-leaflet.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'src', 'map', 'leafletAssets.ts');
const VERSION = '1.9.4';
const BASE = `https://cdnjs.cloudflare.com/ajax/libs/leaflet/${VERSION}`;
const UA = 'JuanTrike-POC/1.0 (bundling the Leaflet map engine)';

async function get(url) {
  let lastErr;
  for (let attempt = 0; attempt < 5; attempt += 1) {
    try {
      const res = await fetch(url, { headers: { 'User-Agent': UA } });
      if (!res.ok) throw new Error(`${url} -> HTTP ${res.status}`);
      return await res.text();
    } catch (err) {
      lastErr = err;
      console.log(`retry ${attempt + 1}: ${err.message}`);
      await new Promise((r) => setTimeout(r, 1500 * (attempt + 1)));
    }
  }
  throw lastErr;
}

const js = await get(`${BASE}/leaflet.js`);
const css = await get(`${BASE}/leaflet.css`);

if (!js.includes('Leaflet') || js.length < 100_000) throw new Error('leaflet.js looks wrong');
if (css.length < 5_000) throw new Error('leaflet.css looks wrong');
if (css.includes('</style')) throw new Error('leaflet.css contains </style; would break the inline <style> block');

// `</script` inside the inlined program would close the tag early. `<\/script`
// is an identity escape in strings, regexes and comments, so it is always safe
// and produces identical JavaScript once the page parses it.
const safeJs = js.replace(/<\/script/g, '<\\/script');

const banner = `// GENERATED by tools/bundle-leaflet.mjs — do not edit by hand.
// Leaflet ${VERSION} (BSD-2-Clause), https://leafletjs.com
// Bundled so the map engine loads with no network at all.
`;

const source = `${banner}
export const LEAFLET_VERSION = '${VERSION}';

export const LEAFLET_CSS = ${JSON.stringify(css)};

export const LEAFLET_JS = ${JSON.stringify(safeJs)};
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, source);
console.log(
  `wrote ${path.relative(ROOT, OUT)} — js ${(js.length / 1024).toFixed(1)} KiB, ` +
    `css ${(css.length / 1024).toFixed(1)} KiB, total ${(source.length / 1024).toFixed(1)} KiB`,
);
